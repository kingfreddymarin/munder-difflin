'use strict';
/**
 * Council brand mark: a round table seen from above, with eight seats around it.
 *
 * Council is the Paramount fork of Munder Difflin. Munder's mark (tools/make-logo.cjs)
 * is a pixel portrait on a brand-yellow rounded SQUARE; this one is a deep-teal
 * DISC with a round table, so the two never read alike in the Dock: different
 * outline (circle vs square), different dominant colour (teal vs yellow),
 * different figure (geometry vs a face).
 *
 * THE SVG IS THE SOURCE OF TRUTH, and every raster is computed from the same
 * shape list, never traced back from a PNG. Pure vector: circles and rounded
 * rects only, no fonts, no gradients, no filters.
 *
 * Full bleed, as Munder's icon is since 20ba890e: the disc meets the canvas
 * edge, so there is no transparent band shrinking it in the Dock.
 *
 * Writes:
 *   build/icon.svg    design source, 1024
 *   build/icon.png    1024 — Linux, and the electron-builder base
 *   build/icon.ico           Windows, 16..256
 *   build/icon.icns          macOS, 16..1024 (via iconutil)
 *   logo-preview/council-{1024,128,32,16}.png   review previews
 *
 *   node tools/make-council-logo.cjs
 *
 * Running tools/make-logo.cjs afterwards puts Munder's mark back in build/.
 */

const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const { execFileSync } = require('node:child_process');

const ROOT = path.resolve(__dirname, '..');

// ── palette ───────────────────────────────────────────────────────────────
const C = {
  ground: [19, 78, 74],     // #134E4A deep teal, the dominant colour
  rim:    [9, 42, 40],      // #092A28 outer ring, separates the disc from any Dock
  table:  [242, 232, 213],  // #F2E8D5 cream tabletop, the brightest shape
  inlay:  [214, 196, 160],  // #D6C4A0 thin ring set into the top
  seat:   [143, 222, 199],  // #8FDEC7 mint seats, bright enough to separate at 16px
  back:   [222, 244, 236]   // #DEF4EC near-white seat backs, on the outside edge
};

// ── geometry (units of a 1024 canvas, centre 512,512) ─────────────────────
const G = {
  rimW: 28,                     // rim band inside the 512 radius
  table: 222,                   // tabletop radius: the brightest, largest shape
  inlayR: 172, inlayW: 14,      // ring set into the top, visible from ~64px up
  seats: 8,
  seatR: 332,                   // seat centre distance from the middle
  seat: { w: 140, h: 96, r: 32 },        // tangential x radial
  back: { w: 170, h: 38, r: 19, out: 70 } // backrest, pushed outward from the seat centre
};

/**
 * One ordered paint list, used by both the SVG writer and the rasteriser.
 * Each entry: { kind: 'circle'|'ring'|'rrect', colour, ...geometry }.
 */
function shapes() {
  const list = [
    { kind: 'circle', r: 512, c: C.rim },
    { kind: 'circle', r: 512 - G.rimW, c: C.ground }
  ];
  for (let i = 0; i < G.seats; i++) {
    const deg = (360 / G.seats) * i;
    list.push({ kind: 'rrect', deg, dist: G.seatR, ...G.seat, c: C.seat });
    list.push({ kind: 'rrect', deg, dist: G.seatR + G.back.out, ...G.back, c: C.back });
  }
  list.push({ kind: 'circle', r: G.table, c: C.table });
  list.push({ kind: 'ring', r: G.inlayR, w: G.inlayW, c: C.inlay });
  return list;
}

// ── SVG ───────────────────────────────────────────────────────────────────
const hex = (c) => '#' + c.map((v) => v.toString(16).padStart(2, '0')).join('').toUpperCase();

function buildSvg() {
  const body = shapes().map((s) => {
    if (s.kind === 'circle') return `  <circle cx="512" cy="512" r="${s.r}" fill="${hex(s.c)}"/>`;
    if (s.kind === 'ring') return `  <circle cx="512" cy="512" r="${s.r}" fill="none" stroke="${hex(s.c)}" stroke-width="${s.w}"/>`;
    // A seat at the top of the table, rotated clockwise into place.
    const x = 512 - s.w / 2, y = 512 - s.dist - s.h / 2;
    const rot = s.deg ? ` transform="rotate(${s.deg} 512 512)"` : '';
    return `  <rect x="${x}" y="${y}" width="${s.w}" height="${s.h}" rx="${s.r}" fill="${hex(s.c)}"${rot}/>`;
  }).join('\n');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <!-- Council — the app mark: a round table seen from above, eight seats around it.
       Generated by tools/make-council-logo.cjs; edit that, not this.
       Pure vector: no fonts, no gradients, no filters. -->
  <title>Council</title>
${body}
</svg>
`;
}

// ── rasteriser ────────────────────────────────────────────────────────────
function sdRoundBox(px, py, hw, hh, r) {
  const qx = Math.abs(px) - (hw - r), qy = Math.abs(py) - (hh - r);
  return Math.hypot(Math.max(qx, 0), Math.max(qy, 0)) + Math.min(Math.max(qx, qy), 0) - r;
}

/** Signed distance (negative inside) from a point on the 1024 canvas to shape s. */
function sd(s, x, y) {
  const dx = x - 512, dy = y - 512;
  if (s.kind === 'circle') return Math.hypot(dx, dy) - s.r;
  if (s.kind === 'ring') return Math.abs(Math.hypot(dx, dy) - s.r) - s.w / 2;
  // Into the seat's own frame: t along the table edge, r outward from the centre.
  const a = (s.deg * Math.PI) / 180, cos = Math.cos(a), sin = Math.sin(a);
  const t = dx * cos + dy * sin;
  const r = dx * sin - dy * cos;
  return sdRoundBox(t, r - s.dist, s.w / 2, s.h / 2, s.r);
}

/**
 * Painter's algorithm per subsample, box-filtered. Small sizes get more
 * subsamples: at 16px a pixel covers 64 canvas units and 4x4 aliases the seats.
 */
function rasterise(N) {
  const list = shapes();
  const SS = N <= 64 ? 8 : 4;
  const k = 1024 / N;
  const out = Buffer.alloc(N * N * 4);
  for (let y = 0; y < N; y++) {
    for (let x = 0; x < N; x++) {
      let cov = 0, r = 0, g = 0, b = 0;
      for (let sy = 0; sy < SS; sy++) {
        for (let sx = 0; sx < SS; sx++) {
          const px = (x + (sx + 0.5) / SS) * k, py = (y + (sy + 0.5) / SS) * k;
          let col = null;
          for (let i = list.length - 1; i >= 0; i--) {
            if (sd(list[i], px, py) <= 0) { col = list[i].c; break; }
          }
          if (!col) continue;
          cov++; r += col[0]; g += col[1]; b += col[2];
        }
      }
      if (!cov) continue;
      const i = (y * N + x) * 4;
      out[i] = Math.round(r / cov); out[i + 1] = Math.round(g / cov); out[i + 2] = Math.round(b / cov);
      out[i + 3] = Math.round((cov / (SS * SS)) * 255);
    }
  }
  return encodePng(N, out);
}

// ── PNG (same encoder as tools/make-logo.cjs) ─────────────────────────────
const CRC = (() => {
  const t = new Int32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let j = 0; j < 8; j++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c;
  }
  return (buf) => {
    let c = -1;
    for (let i = 0; i < buf.length; i++) c = t[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
    return (c ^ -1) >>> 0;
  };
})();

function chunk(type, data) {
  const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4); crc.writeUInt32BE(CRC(td));
  return Buffer.concat([len, td, crc]);
}

function encodePng(N, rgba) {
  const stride = N * 4 + 1;
  const raw = Buffer.alloc(N * stride);
  for (let y = 0; y < N; y++) {
    raw[y * stride] = 0;
    rgba.copy(raw, y * stride + 1, y * N * 4, (y + 1) * N * 4);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(N, 0); ihdr.writeUInt32BE(N, 4);
  ihdr[8] = 8; ihdr[9] = 6;
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlib.deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0))
  ]);
}

/** ICO container of PNG entries (Vista+). 256px is encoded as width byte 0. */
function buildIco(pngs) {
  const dir = Buffer.alloc(6);
  dir.writeUInt16LE(0, 0); dir.writeUInt16LE(1, 2); dir.writeUInt16LE(pngs.length, 4);
  let offset = 6 + pngs.length * 16;
  const entries = [], bodies = [];
  for (const { size, data } of pngs) {
    const e = Buffer.alloc(16);
    e[0] = size >= 256 ? 0 : size;
    e[1] = size >= 256 ? 0 : size;
    e.writeUInt16LE(1, 4); e.writeUInt16LE(32, 6);
    e.writeUInt32LE(data.length, 8); e.writeUInt32LE(offset, 12);
    entries.push(e); bodies.push(data);
    offset += data.length;
  }
  return Buffer.concat([dir, ...entries, ...bodies]);
}

// ── run ───────────────────────────────────────────────────────────────────
const D = (p) => path.join(ROOT, p);
const wrote = [];
const write = (rel, buf) => {
  fs.mkdirSync(path.dirname(D(rel)), { recursive: true });
  fs.writeFileSync(D(rel), buf);
  wrote.push(`${rel.padEnd(32)} ${(buf.length / 1024).toFixed(1)} KB`);
};

const png = new Map();
const at = (n) => { if (!png.has(n)) png.set(n, rasterise(n)); return png.get(n); };

write('build/icon.svg', Buffer.from(buildSvg()));
write('build/icon.png', at(1024));
write('build/icon.ico', buildIco([16, 32, 48, 64, 128, 256].map((size) => ({ size, data: at(size) }))));

const setDir = D('build/icon.iconset');
fs.rmSync(setDir, { recursive: true, force: true });
fs.mkdirSync(setDir, { recursive: true });
for (const [name, size] of [
  ['icon_16x16', 16], ['icon_16x16@2x', 32], ['icon_32x32', 32], ['icon_32x32@2x', 64],
  ['icon_128x128', 128], ['icon_128x128@2x', 256], ['icon_256x256', 256],
  ['icon_256x256@2x', 512], ['icon_512x512', 512], ['icon_512x512@2x', 1024]
]) {
  fs.writeFileSync(path.join(setDir, `${name}.png`), at(size));
}
execFileSync('iconutil', ['-c', 'icns', setDir, '-o', D('build/icon.icns')]);
fs.rmSync(setDir, { recursive: true, force: true });
wrote.push(`build/icon.icns                  ${(fs.statSync(D('build/icon.icns')).size / 1024).toFixed(1)} KB`);

for (const n of [1024, 128, 32, 16]) write(`logo-preview/council-${n}.png`, at(n));

console.log(wrote.join('\n'));
