'use strict';
/**
 * NSC-263: Paramount brand mark pipeline.
 *
 * SOURCE: build/brand/paramount-logo@2x.png (554px, Figma-rendered dark tile + gold N)
 *         build/brand/paramount-logo.svg    (Figma source, kept as vector reference)
 *
 * Writes:
 *   build/icon.svg                  — SVG wrapper (embeds the PNG as data URI)
 *   build/icon.png               1024 — electron-builder base
 *   build/icon.ico                   — Windows multi-size
 *   build/icon.icns                  — macOS via iconutil
 *   docs/logo.png                 512 — @brand/logo.png, used in renderer
 *   ui/src/assets/nasstro-mark.png 128 — in-app sidebar mark (displayed at size-8)
 *   ui/src/assets/paramount-mark.svg — SVG mark (copy of Figma source)
 *
 *   node tools/make-brand.cjs
 */

const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const { execFileSync } = require('node:child_process');

const ROOT = path.resolve(__dirname, '..');
const SRC_PNG = path.join(ROOT, 'build/brand/paramount-logo@2x.png');
const SRC_SVG = path.join(ROOT, 'build/brand/paramount-logo.svg');

const D = (p) => path.join(ROOT, p);
const wrote = [];

// ── sips resize ───────────────────────────────────────────────────────────────
function sipsResize(srcPath, destPath, size) {
  fs.mkdirSync(path.dirname(destPath), { recursive: true });
  execFileSync('sips', ['-z', String(size), String(size), srcPath, '--out', destPath]);
  wrote.push(`${path.relative(ROOT, destPath).padEnd(36)} ${(fs.statSync(destPath).size / 1024).toFixed(1)} KB`);
}

// ── ICO builder (PNG container, Vista+) ───────────────────────────────────────
function buildIco(pngPaths) {
  const pngs = pngPaths.map((p) => ({ size: parseInt(path.basename(p)), data: fs.readFileSync(p) }));
  const dir = Buffer.alloc(6);
  dir.writeUInt16LE(0, 0); dir.writeUInt16LE(1, 2); dir.writeUInt16LE(pngs.length, 4);
  let offset = 6 + pngs.length * 16;
  const entries = [], bodies = [];
  for (const { size, data } of pngs) {
    const e = Buffer.alloc(16);
    e[0] = size >= 256 ? 0 : size;
    e[1] = size >= 256 ? 0 : size;
    e[2] = 0; e[3] = 0;
    e.writeUInt16LE(1, 4); e.writeUInt16LE(32, 6);
    e.writeUInt32LE(data.length, 8); e.writeUInt32LE(offset, 12);
    entries.push(e); bodies.push(data);
    offset += data.length;
  }
  return Buffer.concat([dir, ...entries, ...bodies]);
}

// ── step 1: generate 1024 master ──────────────────────────────────────────────
const master1024 = D('build/icon.png');
sipsResize(SRC_PNG, master1024, 1024);

// ── step 2: docs/logo.png (512, used by @brand/logo.png → renderer) ──────────
sipsResize(SRC_PNG, D('docs/logo.png'), 512);

// ── step 3: in-app sidebar mark (128px, rendered at size-8=32px) ─────────────
sipsResize(SRC_PNG, D('ui/src/assets/nasstro-mark.png'), 128);

// ── step 4: build/icon.svg (SVG wrapper embedding the source PNG as data URI) ─
const pngB64 = fs.readFileSync(SRC_PNG).toString('base64');
const iconSvg = `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="1024" height="1024" viewBox="0 0 1024 1024">
  <!-- Paramount brand mark — NSC-263. Source: build/brand/paramount-logo.svg (Figma export).
       Generated by tools/make-brand.cjs; edit that, not this. -->
  <title>Paramount</title>
  <image width="1024" height="1024" xlink:href="data:image/png;base64,${pngB64}"/>
</svg>
`;
fs.writeFileSync(D('build/icon.svg'), iconSvg);
wrote.push(`build/icon.svg                       ${(iconSvg.length / 1024).toFixed(1)} KB`);

// ── step 5: ui/src/assets/paramount-mark.svg (copy Figma source) ─────────────
fs.copyFileSync(SRC_SVG, D('ui/src/assets/paramount-mark.svg'));
wrote.push(`ui/src/assets/paramount-mark.svg     ${(fs.statSync(SRC_SVG).size / 1024).toFixed(1)} KB`);

// ── step 6: build/icon.ico (multi-size) ──────────────────────────────────────
const icoTmp = require('node:os').tmpdir();
const icoSizes = [16, 32, 48, 64, 128, 256];
const icoPngs = icoSizes.map((s) => {
  const p = path.join(icoTmp, `${s}.png`);   // basename must start with the size digit for parseInt
  sipsResize(SRC_PNG, p, s);
  return p;
});
const icoData = buildIco(icoPngs);
fs.writeFileSync(D('build/icon.ico'), icoData);
wrote.push(`build/icon.ico                       ${(icoData.length / 1024).toFixed(1)} KB`);

// ── step 7: build/icon.icns (macOS, iconutil) ─────────────────────────────────
const setDir = D('build/icon.iconset');
fs.rmSync(setDir, { recursive: true, force: true });
fs.mkdirSync(setDir, { recursive: true });
const icnsSpec = [
  ['icon_16x16', 16], ['icon_16x16@2x', 32], ['icon_32x32', 32], ['icon_32x32@2x', 64],
  ['icon_128x128', 128], ['icon_128x128@2x', 256], ['icon_256x256', 256],
  ['icon_256x256@2x', 512], ['icon_512x512', 512], ['icon_512x512@2x', 1024],
];
for (const [name, size] of icnsSpec) {
  sipsResize(SRC_PNG, path.join(setDir, `${name}.png`), size);
}
execFileSync('iconutil', ['-c', 'icns', setDir, '-o', D('build/icon.icns')]);
fs.rmSync(setDir, { recursive: true, force: true });
wrote.push(`build/icon.icns                      ${(fs.statSync(D('build/icon.icns')).size / 1024).toFixed(1)} KB`);

console.log('\nWrote:');
console.log(wrote.join('\n'));
